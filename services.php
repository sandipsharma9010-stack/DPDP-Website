    <script>
    function toggleCard(id) {
        let content = document.getElementById(id);
        let allContents = document.querySelectorAll('.hidden-content, .visible-content');
        allContents.forEach(el => {
            if (el !== content) el.classList.remove('visible-content');
            el.classList.add('hidden-content');
        });
        content.classList.toggle('hidden-content');
        content.classList.toggle('visible-content');
    }





    function toggleCard(id) {
        // Hide all content divs
        document.querySelectorAll('.visible-content, .hidden-content').forEach(div => {
            div.style.display = 'none';
        });

        // Show the clicked div
        let selectedDiv = document.getElementById(id);
        if (selectedDiv) {
            selectedDiv.style.display = 'block';
        }
    }

    // Ensure the first div (Healthcare) is open on page load
    document.addEventListener("DOMContentLoaded", function() {
        toggleCard('healthcare');
    });




    function toggleContent(clickedElement) {
        // Close all other divs first
        document.querySelectorAll(".expandable-smooths").forEach(div => {
            if (div !== clickedElement) {
                div.classList.remove("active");
                div.querySelector(".contents").style.display = "none";
            }
        });

        // Toggle the clicked div
        let contents = clickedElement.querySelector(".contents");
        let isVisible = contents.style.display === "block";

        if (isVisible) {
            contents.style.display = "none";
            clickedElement.classList.remove("active");
        } else {
            contents.style.display = "block";
            clickedElement.classList.add("active");
        }
    }
    </script>

