                    <h3 class="mt-3">Liability for Data Breach under the DPDP Act</h3>
                    <p class="sub-para">The DPDP Act places liability on the data fiduciary for any non-compliance by the data
                        processor. If a data breach occurs as a result of the processor's actions, the data
                        fiduciary is responsible for ensuring they have:
                    </p>
                    <ol class="data-list mt-3">
                        <li>Exercised due diligence in selecting the processor: The fiduciary must show that they
                            took all reasonable steps to ensure the processor had adequate data protection measures
                            in place.
                        </li>
                        <li>Imposed proper contractual obligations: The fiduciary must have put in place a solid
                            contract that ensures the processor complies with the provisions of the DPDP Act.
                        </li>
                    </ol>
                    <p class="sub-para">In simpler terms, if a data breach occurs, the fiduciary must prove they acted responsibly in
